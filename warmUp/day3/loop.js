/* for loop have 3 conditin
1. intilization
2. condition
3. increment/decrement(change)
*/

//forward loop
for (let i = 0; i < 5; i++) {
  console.log(i);
}

// reverse loop
for (let i = 5; i > 0; i--) {
  console.log(i);
}

//while loop
let i = 0;
while (i < 5) {
  console.log("Hello world " + i);
  i++;
}
